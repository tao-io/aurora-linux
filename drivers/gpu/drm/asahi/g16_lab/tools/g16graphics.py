"""Generate small M4 graphics shader bodies; no capture or Metal input.

Arithmetic and loads use the locally qualified assembler. Aurora AGX3b emits
vertex exports, varying staging copies, and fragment interpolation. The four
position-publication operations and tile-store tail retain the qualified ABI.
Generated state loaders are optional; tile helpers remain reference programs.
"""
import argparse
from pathlib import Path

from g16mandelbrot import assemble_g16
from g16agx3 import Encoder


def position_publication():
    return bytes.fromhex('0b0029c4' '1b032f00420000040000'
                         '2b002600400000080000' '3c80233e0000000c4060')


def vertex(encoder):
    # u0:u1 = float2 vertex buffer, sr93 = vertex ID. Preserve the ESL
    # dependency wait 0 and the export move's load-completion wait 5.
    source = """get_sr 0, r0, sr93
device_load 5, i32, xy, r0_r1, u0_u1, r0.discard, lsl 3, 0, wait 0, 1, 0, 0
stop
"""
    body = assemble_g16(source)[:-2]
    # Publish x,y,0,1 into the fixed M4 position-export registers u0..u3.
    # Then export the four position components with their final-write masks.
    body += position_publication()
    for component in range(4):
        body += encoder.export(component * 2, component, component + 1, 1 << component)
    body += bytes.fromhex('0e00')
    return source, body


def fragment():
    # M4 RGBA8 tile store takes four packed UNORM8 channels in r0.
    # Emit red, deliberately different from the fixture's blue/purple color.
    source = """pack rg8unorm, r0l, 1.0, 0.0
pack rg8unorm, r0h, 0.0, 1.0
stop
"""
    body = bytearray(assemble_g16(source)[:-2])
    # The M4 first low-half packing operation carries bit 11; retain its
    # observed publication control while using newly encoded color operands.
    body[1] |= 0x08
    # Fixed M4 fragment tile-store synchronization and r0 publication.
    body += bytes.fromhex('870254000600' '8702540c0800'
                          'e70654000000014e00000000' '0702540c0200' '0e00')
    return source, body


def fragment_xy(triangle=False):
    # Diagnostic fragment coordinates, not vertex-varying interpolation.
    source = """get_sr 0, r0, sr32
convert u32_to_f, r0, r0, rte
fmul r0, r0, 0.0625
fmul r0, r0, 0.0625
get_sr 0, r1, sr33
convert u32_to_f, r1, r1, rte
fmul r1, r1, 0.0625
fmul r1, r1, 0.0625
"""
    body = assemble_g16(source + 'stop\n')[:-2]
    if triangle:
        body += assemble_g16('fadd r1, r1, r0.neg\nstop\n')[:-2]
    packing = bytearray(assemble_g16(('pack rg8unorm, r0l, r1, r0\n' if triangle else
                                     'pack rg8unorm, r0l, r0, r1\n') + 'stop\n')[:-2])
    packing[1] |= 0x08
    body += packing
    if triangle:
        body += assemble_g16('get_sr 0, r1, sr33\nconvert u32_to_f, r1, r1, rte\n'
                             'fmul r1, r1, 0.0625\nfmul r1, r1, 0.0625\n'
                             'fadd r1, 1.0, r1.neg\npack rg8unorm, r0h, r1, 1.0\nstop\n')[:-2]
    else:
        body += assemble_g16('pack rg8unorm, r0h, 0.0, 1.0\nstop\n')[:-2]
    body += fragment()[1][-32:]
    return source, body


def vertex_varying(encoder):
    # float4 input records contain x, y, color, padding. Stage all outputs
    # before exporting, retaining the proven position publication sequence.
    source = ('get_sr 0, r0, sr93\n'
              'device_load 5, i32, xyz, r0_r1_r2, u0_u1, r0.discard, lsl 4, 0, wait 0, 1, 0, 0\n')
    body = assemble_g16(source + 'stop\n')[:-2]
    body += position_publication()
    # Diagnostic GPU readback of the attribute, after the position COPY has
    # waited for the input load. The readback allocation is separately mapped
    # writable, with three words at +0x1000 indexed by vertex ID.
    body += assemble_g16('mov_imm r6, 0xa9000\nmov_imm r7, 0x100\n'
                         'get_sr 0, r8, sr93\n'
                         'device_store 0, i32, x, r2, r6_r7, r8, lsl 2, 0, wait 0, 1, 1\nstop\n')[:-2]
    body += encoder.stage(8, 4, 5)
    for component in range(5):
        body += encoder.export(component * 2, component, component + 1, 1 << component)
    return source, body + bytes.fromhex('0e00')


def fragment_varying(encoder):
    # Coefficient zero is a linear vertex attribute. No pixel-coordinate SR
    # read or coordinate-derived arithmetic contributes to the color.
    body = encoder.interpolate(0, 0, first=True)
    packing = bytearray(assemble_g16('pack rg8unorm, r0l, r0, 0.0\nstop\n')[:-2])
    packing[1] |= 0x08
    body += packing
    body += assemble_g16('pack rg8unorm, r0h, 0.0, 1.0\nstop\n')[:-2]
    return 'linear coefficient 0 -> red', body + fragment()[1][-32:]


def header(encoder):
    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* Generated by tools/g16graphics.py; do not edit. */',
             '#ifndef G16_GENERATED_GRAPHICS_H', '#define G16_GENERATED_GRAPHICS_H']
    for name, producer, capacity in [('vertex', lambda: vertex(encoder), 128), ('fragment', fragment, 64),
                                     ('fragment_xy', fragment_xy, 4096),
                                     ('fragment_triangle', lambda: fragment_xy(True), 4096),
                                     ('vertex_varying', lambda: vertex_varying(encoder), 4096),
                                     ('fragment_varying', lambda: fragment_varying(encoder), 4096)]:
        source, code = producer()
        if len(code) > capacity:
            raise ValueError(f'{name} exceeds its bounded shader slot')
        lines += [f'/* {name}: {len(code)} bytes; see generator for fixed export ABI. */',
                  f'static const u8 g16_generated_{name}[] = {{']
        for offset in range(0, len(code), 12):
            lines.append('\t' + ', '.join(f'0x{x:02x}' for x in code[offset:offset+12]) + ',')
        lines.append('};')
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--agx3-library', type=Path, required=True)
    args = parser.parse_args()
    args.header.write_text(header(Encoder(args.agx3_library)))
