"""Emit bounded M4 vertex/fragment state loaders from explicit bindings.

The qualified no-varying stage controls and helper-call ABI are fixed here.
This is not a general LoadShader encoder or a replacement for tile helpers.
No capture file is read by the generator.
"""
import argparse
from pathlib import Path
from g16mandelbrot import assemble_g16
import applegpu


def mov32(register, value):
    if not 0 <= value < 1 << 32:
        raise ValueError('32-bit immediate required')
    desc = applegpu.MovImm32InstructionDesc()
    fields = {}
    desc.encode_strings('mov_imm', fields, [register, str(value)])
    return desc.encode_fields(fields)


def code(source):
    return assemble_g16(source + '\nstop\n')[:-2]


def load_shader(stage, address):
    if stage not in ('vertex', 'fragment') or not 0 < address < 1 << 42 or address & 63:
        raise ValueError('M4 stage and aligned 42-bit shader address required')
    vertex = stage == 'vertex'
    control = 0x412a0077 if vertex else 0x4b432a0077
    main = ((address << 17) | 0x2a0177).to_bytes(8, 'little')
    auxiliary = 0x2002a00f7 if vertex else 0x2a00f7
    return (control.to_bytes(8, 'little') + main + bytes((0 if vertex else 4, 0))
            + auxiliary.to_bytes(10, 'little'))


def loader(stage, main, bindings=0x1000014d000, draw_args=0x1000014d200):
    body = b''
    if stage == 'vertex':
        for reg, pointer in [(2, bindings), (20, draw_args)]:
            if not 0 < pointer < 1 << 42 or pointer & 7:
                raise ValueError('aligned binding address required')
            body += mov32(f'r{reg}', pointer & 0xffffffff)
            body += mov32(f'r{reg + 1}', pointer >> 32)
        body += code('device_load 1, i32, xy, r18_r19, r2_r3, 0, lsl 2, 0, 1, 1, 0\n'
                     'device_load 1, i32, xy, r20_r21, r20_r21, 0, lsl 2, 0, 1, 1, 1')
    body += load_shader(stage, main)
    body += mov32('r1', 0)
    # Select the qualified long form of the SR1 read, preserving its length bit.
    sr = int.from_bytes(code('get_sr 0, r1l, sr1'), 'little') | 1 << 16
    body += sr.to_bytes(8, 'little')
    body += mov32('r0', 0x200 if stage == 'vertex' else 0x100)
    body += code('iadd r0, r0, r1, lsl 4, wait 0')
    body += mov32('r1', 0x100)
    body += bytes.fromhex('0f1254004c00')  # indirect helper call via r0:r1
    if stage == 'vertex':
        body += code('mov u0, r18.discard, wait 1\nmov u1, r19.discard\n'
                     'mov u2, r20.discard\nmov u3, r21.discard')
        body += bytes.fromhex('03000700020000006000')  # fixed publication control
    else:
        body += bytes.fromhex('070254f30200')  # fixed fragment publication control
    return body + bytes.fromhex('0e00')


def header():
    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* Generated by tools/g16bindings.py; fixed no-varying helper ABI. */',
             '#ifndef G16_GENERATED_BINDINGS_H', '#define G16_GENERATED_BINDINGS_H']
    for name, stage, main in [('vertex', 'vertex', 0x10000000540),
                              ('fragment', 'fragment', 0x1000014f000),
                              ('vertex_varying', 'vertex', 0x1000014d800)]:
        data = loader(stage, main)
        if len(data) > 0x400:
            raise ValueError('loader exceeds slot')
        lines.append(f'static const u8 g16_generated_{name}_loader[] = {{')
        for offset in range(0, len(data), 12):
            lines.append('\t' + ', '.join(f'0x{x:02x}' for x in data[offset:offset+12]) + ',')
        lines.append('};')
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path, required=True)
    args = parser.parse_args()
    args.header.write_text(header())
