#!/usr/bin/env python3
"""Check M4 config owners and IOMapping encoding against an immutable old producer.

Preserves the baseline's tuple data solely in the generated host fixture. No
baseline tuple or generated bytes are consumed by production driver code.
"""
import argparse,ast,hashlib,json,re,subprocess
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--kernel',type=Path,required=True)
p.add_argument('--baseline',required=True);p.add_argument('--output',type=Path,required=True)
a=p.parse_args();a.output.mkdir(parents=True,exist_ok=False);base='drivers/gpu/drm/asahi'
tree=subprocess.check_output(['git','-C',str(a.kernel),'rev-parse',a.baseline+'^{tree}'],text=True).strip()
src=subprocess.check_output(['git','-C',str(a.kernel),'show',f'{tree}:{base}/g16_config.rs'],text=True)
(a.output/'baseline.rs').write_text(src)
def table(name):return ast.literal_eval('['+re.search(r'const '+name+r':.*?= &\[(.*?)\];',src,re.S).group(1)+']')
sizes=table('SIZES');maps=table('IOMAPS')
names=[n.strip() for n in re.search(r'enum Object \{(.*?)\n\}',src,re.S).group(1).split(',') if n.strip()]
raw=(a.kernel/base/'g16_config_layout.rs').read_bytes();(a.output/'g16_config_layout.rs').write_bytes(raw)
fixture=(a.kernel/base/'tools/m4_config_layout_tests.rs').read_text()
fixture=fixture.replace('/* BASELINE_OWNERS */',','.join('Object::'+n for n in names))
fixture=fixture.replace('/* BASELINE_SIZES */',','.join(map(str,sizes)))
fixture=fixture.replace('/* BASELINE_IOMAPS */',','.join(str(tuple(m)) for m in maps))
(a.output/'tests.rs').write_text(fixture)
subprocess.run(['rustc','--edition=2021','-A','dead_code','--test',str(a.output/'tests.rs'),'-o',str(a.output/'tests')],check=True)
subprocess.run([str((a.output/'tests').resolve())],check=True)
(a.output/'inputs.json').write_text(json.dumps(dict(baseline_tree=tree,baseline_sha256=hashlib.sha256(src.encode()).hexdigest(),layout_sha256=hashlib.sha256(raw).hexdigest(),fixture_sha256=hashlib.sha256(fixture.encode()).hexdigest()),indent=2)+'\n')
